#!/usr/bin/env node

const cdpPort = Number(process.env.CONVERSATION_DASHBOARD_CDP_PORT || 9237);
const pages = await fetch(`http://127.0.0.1:${cdpPort}/json/list`).then(response => response.json());
const page = pages.find(target => target.type === "page" && target.url === "app://-/index.html");
if (!page) throw new Error("Aboard window not found");

const socket = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((resolve, reject) => {
  socket.addEventListener("open", resolve, { once: true });
  socket.addEventListener("error", reject, { once: true });
});

let nextId = 0;
const pending = new Map();
socket.addEventListener("message", event => {
  const message = JSON.parse(event.data);
  const callback = pending.get(message.id);
  if (!callback) return;
  pending.delete(message.id);
  callback(message);
});
const send = (method, params = {}) => new Promise(resolve => {
  const id = ++nextId;
  pending.set(id, resolve);
  socket.send(JSON.stringify({ id, method, params }));
});

// The preceding installed regression may finish while Chromium still has a
// physical pointer transition queued. Establish a real input boundary before
// installing the counters below, otherwise that delayed event can be mistaken
// for a PointerEvent generated by this deliberately mouse-only fixture.
await send("Input.dispatchMouseEvent", {
  type: "mouseReleased",
  x: 8,
  y: 8,
  button: "left",
  buttons: 0
});
await send("Input.dispatchMouseEvent", {
  type: "mouseMoved",
  x: 1,
  y: 1,
  button: "none",
  buttons: 0
});
await send("Input.dispatchKeyEvent", { type: "keyDown", key: "Escape", code: "Escape", windowsVirtualKeyCode: 27 });
await send("Input.dispatchKeyEvent", { type: "keyUp", key: "Escape", code: "Escape", windowsVirtualKeyCode: 27 });
await new Promise(resolve => setTimeout(resolve, 180));

const response = await send("Runtime.evaluate", {
  expression: `(async () => {
    const sleep = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds));
    const mouse = (view, type, x, y, buttons) => new view.MouseEvent(type, {
      bubbles: true,
      cancelable: true,
      composed: true,
      button: 0,
      buttons,
      clientX: x,
      clientY: y,
      view
    });
    const entry = document.getElementById("conversation-dashboard-sidebar-entry");
    const surface = document.getElementById("conversation-dashboard-surface");
    document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
    entry?.click();
    await sleep(100);

    const frame = surface?.querySelector("iframe");
    const doc = frame?.contentDocument;
    const workTarget = [...(doc?.querySelectorAll('[data-drop-kind="work"]') || [])].find(target => {
      const rect = target.getBoundingClientRect();
      return rect.width > 100 && rect.height > 80;
    });
    const chatTarget = doc?.querySelector('.chat-list[data-drop-kind="chat"]')
      || doc?.querySelector('[data-drop-kind="chat"]');
    const baseRow = [...document.querySelectorAll("[data-app-action-sidebar-thread-row]")].find(row => {
      const rect = row.getBoundingClientRect();
      return rect.top >= 0 && rect.bottom <= window.innerHeight
        && row.dataset.appActionSidebarThreadKind === "local";
    });
    if (!entry || !surface || !frame || !doc || !workTarget || !chatTarget || !baseRow) {
      return { ok: false, reason: "Mouse-only source or targets unavailable" };
    }

    const storageKey = "conversation-dashboard-board-v1";
    const originalBoard = localStorage.getItem(storageKey);
    const verificationId = "44444444-4444-4444-8444-444444444443";
    const verificationUrl = "codex://threads/" + verificationId;
    const row = baseRow.cloneNode(true);
    row.removeAttribute("draggable");
    row.removeAttribute("aria-selected");
    row.removeAttribute("aria-checked");
    row.removeAttribute("data-state");
    delete row.dataset.conversationDashboardDraggable;
    delete row.dataset.conversationDashboardDragListener;
    delete row.dataset.aboardDragging;
    row.dataset.appActionSidebarThreadId = "local:" + verificationId;
    row.dataset.appActionSidebarThreadKind = "local";
    row.dataset.appActionSidebarThreadTitle = "Mouse-only Work import";
    row.dataset.appActionSidebarThreadSelected = "false";
    baseRow.parentElement.appendChild(row);
    await sleep(60);

    let hostPointerEvents = 0;
    let childPointerEvents = 0;
    const countHostPointer = event => {
      if (event.target === row || row.contains(event.target)) hostPointerEvents += 1;
    };
    const countChildPointer = event => {
      if (event.target?.closest?.("[data-drop-kind]") === workTarget
        || event.target?.closest?.("[data-drop-kind]") === chatTarget) childPointerEvents += 1;
    };
    for (const type of ["pointerdown", "pointermove", "pointerup", "pointercancel"]) {
      document.addEventListener(type, countHostPointer, true);
      doc.addEventListener(type, countChildPointer, true);
    }

    const clearPointerCounters = () => {
      hostPointerEvents = 0;
      childPointerEvents = 0;
    };
    const clearGesture = async () => {
      document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
      await sleep(50);
    };
    const startMouseDrag = async () => {
      await clearGesture();
      clearPointerCounters();
      const rect = row.getBoundingClientRect();
      const x = rect.left + Math.min(80, rect.width / 3);
      const y = rect.top + rect.height / 2;
      row.dispatchEvent(mouse(window, "mousedown", x, y, 1));
      document.dispatchEvent(mouse(window, "mousemove", x + 4, y, 1));
      await sleep(35);
      const belowThresholdStarted = Boolean(window.__conversationDashboardDragSession);
      document.dispatchEvent(mouse(window, "mousemove", x + 10, y, 1));
      await sleep(45);
      return {
        belowThresholdStarted,
        started: window.__conversationDashboardDragSession?.source === "host-pointer",
        sessionId: window.__conversationDashboardDragSession?.id || "",
        payloadId: window.__conversationDashboardDragSession?.payload?.id || ""
      };
    };
    const childPoint = target => {
      const rect = target.getBoundingClientRect();
      return {
        x: rect.left + Math.min(28, rect.width / 2),
        y: rect.top + Math.min(28, rect.height / 2)
      };
    };
    const cleanState = () => !window.__conversationDashboardDragSession
      && !window.__conversationDashboardDraggedThread
      && !document.documentElement.dataset.conversationDashboardDragging
      && row.dataset.aboardDragging !== "true"
      && doc.getElementById("drag-guide")?.classList.contains("show") !== true
      && doc.querySelectorAll(".is-drop-active, .is-drop-invalid").length === 0;

    let result;
    try {
      clearPointerCounters();
      const validStart = await startMouseDrag();
      const workPoint = childPoint(workTarget);
      workTarget.dispatchEvent(mouse(frame.contentWindow, "mousemove", workPoint.x, workPoint.y, 1));
      await sleep(45);
      const validHighlighted = workTarget.classList.contains("is-drop-active")
        && !workTarget.classList.contains("is-drop-invalid");
      workTarget.dispatchEvent(mouse(frame.contentWindow, "mouseup", workPoint.x, workPoint.y, 0));
      await sleep(420);
      const imported = frame.contentWindow.eval("board.items.filter(item => item.url === " + JSON.stringify(verificationUrl) + ")");
      const valid = {
        belowThresholdDidNotStart: !validStart.belowThresholdStarted,
        aboveThresholdStarted: validStart.started && Boolean(validStart.sessionId),
        correctPayload: validStart.payloadId === verificationId,
        highlighted: validHighlighted,
        importedOnce: imported.length === 1,
        importedAsWork: imported[0]?.kind === "work" && imported[0]?.projectId === workTarget.dataset.projectId,
        cleaned: cleanState(),
        mouseOnly: hostPointerEvents === 0 && childPointerEvents === 0
      };

      await clearGesture();
      clearPointerCounters();
      const beforeInvalid = JSON.stringify(frame.contentWindow.eval("board"));
      const invalidStart = await startMouseDrag();
      const currentChatTarget = doc.querySelector('.chat-list[data-drop-kind="chat"]')
        || doc.querySelector('[data-drop-kind="chat"]');
      const chatPoint = childPoint(currentChatTarget);
      currentChatTarget.dispatchEvent(mouse(frame.contentWindow, "mousemove", chatPoint.x, chatPoint.y, 1));
      await sleep(45);
      const invalidHighlighted = currentChatTarget.classList.contains("is-drop-invalid")
        && !currentChatTarget.classList.contains("is-drop-active");
      currentChatTarget.dispatchEvent(mouse(frame.contentWindow, "mouseup", chatPoint.x, chatPoint.y, 0));
      await sleep(220);
      const afterInvalid = JSON.stringify(frame.contentWindow.eval("board"));
      const invalid = {
        aboveThresholdStarted: invalidStart.started,
        highlighted: invalidHighlighted,
        boardUnchanged: afterInvalid === beforeInvalid,
        rejected: /不能移入|类型不匹配/.test(doc.getElementById("toast")?.textContent || ""),
        cleaned: cleanState(),
        mouseOnly: hostPointerEvents === 0 && childPointerEvents === 0
      };

      await clearGesture();
      clearPointerCounters();
      // A completed drag deliberately suppresses the immediately following
      // click. Wait past that guard before validating an ordinary row click.
      await sleep(500);
      const handoffEndpoint = "http://127.0.0.1:47844/api/handoff";
      const originalFetchDescriptor = Object.getOwnPropertyDescriptor(window, "fetch");
      const originalFetch = window.fetch;
      const originalHttpTestBridgeDescriptor = Object.getOwnPropertyDescriptor(window, "__conversationDashboardUseHttpTestBridge");
      const handoffRequests = [];
      const inlineButton = document.createElement("button");
      inlineButton.type = "button";
      inlineButton.hidden = true;
      inlineButton.textContent = "Mouse-only inline action";
      row.appendChild(inlineButton);
      let nativeRowClickCount = 0;
      let inlineClickCount = 0;
      row.addEventListener("click", event => {
        nativeRowClickCount += 1;
      });
      inlineButton.addEventListener("click", () => { inlineClickCount += 1; });
      const rowRect = row.getBoundingClientRect();
      const clickX = rowRect.left + Math.min(80, rowRect.width / 3);
      const clickY = rowRect.top + rowRect.height / 2;
      let noMoveStarted = null;
      let inlineClickPrevented = null;
      let nativeClickOnePrevented = null;
      let nativeClickTwoPrevented = null;
      let handoffBridgeOnce = false;
      Object.defineProperty(window, "fetch", {
        configurable: true,
        enumerable: originalFetchDescriptor?.enumerable ?? true,
        writable: true,
        value: async (url, options = {}) => {
          if (String(url || "") !== handoffEndpoint) {
            return Reflect.apply(originalFetch, window, [url, options]);
          }
          let body = null;
          try { body = JSON.parse(String(options.body || "null")); } catch (_) {}
          handoffRequests.push({
            url: String(url || ""),
            method: String(options.method || "GET").toUpperCase(),
            body
          });
          return { ok: true, status: 202 };
        }
      });
      try {
        Object.defineProperty(window, "__conversationDashboardUseHttpTestBridge", {
          configurable: true,
          enumerable: originalHttpTestBridgeDescriptor?.enumerable ?? true,
          writable: true,
          value: true
        });
        const inlineEvent = mouse(window, "click", clickX, clickY, 0);
        inlineButton.dispatchEvent(inlineEvent);
        inlineClickPrevented = inlineEvent.defaultPrevented;

        row.dispatchEvent(mouse(window, "mousedown", clickX, clickY, 1));
        row.dispatchEvent(mouse(window, "mouseup", clickX, clickY, 0));
        await sleep(35);
        noMoveStarted = Boolean(window.__conversationDashboardDragSession);
        const nativeClickOne = mouse(window, "click", clickX, clickY, 0);
        const nativeClickTwo = mouse(window, "click", clickX, clickY, 0);
        row.dispatchEvent(nativeClickOne);
        row.dispatchEvent(nativeClickTwo);
        nativeClickOnePrevented = nativeClickOne.defaultPrevented;
        nativeClickTwoPrevented = nativeClickTwo.defaultPrevented;
        await sleep(120);
        const request = handoffRequests[0];
        handoffBridgeOnce = handoffRequests.length === 1
          && request?.url === handoffEndpoint
          && request?.method === "POST"
          && request?.body?.id === verificationId;
      } finally {
        if (originalHttpTestBridgeDescriptor) Object.defineProperty(window, "__conversationDashboardUseHttpTestBridge", originalHttpTestBridgeDescriptor);
        else delete window.__conversationDashboardUseHttpTestBridge;
        if (originalFetchDescriptor) Object.defineProperty(window, "fetch", originalFetchDescriptor);
        else delete window.fetch;
        inlineButton.remove();
      }
      const click = {
        noMoveDidNotStart: !noMoveStarted,
        nativeClicksIntercepted: nativeClickOnePrevented && nativeClickTwoPrevented,
        nativeRowNotActivated: nativeRowClickCount === 1,
        inlineButtonDelivered: inlineClickCount === 1,
        inlineButtonNotPrevented: inlineClickPrevented === false,
        handoffBridgeOnce,
        dashboardRemainsVisible: surface.dataset.active === "true",
        mouseOnly: hostPointerEvents === 0 && childPointerEvents === 0,
        cleaned: !window.__conversationDashboardDragSession
          && !window.__conversationDashboardDraggedThread
          && !document.documentElement.dataset.conversationDashboardDragging
      };

      result = {
        ok: Object.values(valid).every(Boolean)
          && Object.values(invalid).every(Boolean)
          && Object.values(click).every(Boolean),
        version: window.__conversationDashboardVersion,
        valid,
        invalid,
        click
      };
    } finally {
      for (const type of ["pointerdown", "pointermove", "pointerup", "pointercancel"]) {
        document.removeEventListener(type, countHostPointer, true);
        doc.removeEventListener(type, countChildPointer, true);
      }
      document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
      frame.contentWindow.eval("clearTimeout(saveTimer); saveTimer = null");
      if (originalBoard == null) localStorage.removeItem(storageKey);
      else localStorage.setItem(storageKey, originalBoard);
      frame.contentWindow.eval("(() => { let restored = fallbackBoard; try { const raw = window.parent.localStorage.getItem(storageKey); if (raw) restored = JSON.parse(raw); } catch (_) {} board = normalizeBoard(restored); activeTab = board.defaultTab || 'professional'; query = ''; modal = null; floatingMenu = null; internalDrag = null; render(); clearTimeout(saveTimer); saveTimer = null; })()");
      row.remove();
      entry.click();
      await sleep(80);
    }
    result.boardRestored = localStorage.getItem(storageKey) === originalBoard;
    result.ok = result.ok && result.boardRestored;
    return result;
  })()`,
  awaitPromise: true,
  returnByValue: true
});

socket.close();
const result = response.result?.result?.value;
if (!result) console.error(JSON.stringify(response, null, 2));
else console.log(JSON.stringify(result, null, 2));
if (!result?.ok) process.exitCode = 1;
